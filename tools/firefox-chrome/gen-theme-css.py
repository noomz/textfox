#!/usr/bin/env python3
"""Generate chrome/theme.css: Firefox theme colors onto textfox surfaces (V22, T35).

CSS has no `if()` in Firefox 160, so each surface's pick between the theme's color pair and
textfox's fallback is arithmetic on colors (relative color syntax and color-mix()):

1. The theme's background is composited over the paint under it (srgb, as Firefox paints), and
   its text over that.
2. Both relative luminances (xyz-d65 `y`, WCAG's luminance) are packed into one color, so one
   relative color can compute the contrast test. Its result, 1 (pass) or 0, rides as the alpha
   of black (`-s`), multiplied by --tf-theme-colors (clamped 0..1).
3. A pick returns the theme color when s is 1 and the fallback, its alpha kept, when s is 0:
   premultiplied color-mix() with the weights carried as alphas.

A pair's capture block only matches when the theme sets its background key: Firefox writes a set
key into the root's style attribute and leaves an unset one out. Without a theme, or with the key
unset, nothing here is defined and defaults.css falls back to --tf-bg and --tf-fg.

Usage: gen-theme-css.py [--check]   (writes chrome/theme.css; --check exits 1 if it is stale)
"""
import argparse
from pathlib import Path
import sys

OUT = Path(__file__).resolve().parents[2] / 'chrome' / 'theme.css'

# name, theme background key (Firefox variable), theme text, backing the background lies over,
# fallback background, fallback text. The window pair is --tf-bg itself, so only its text is gated.
PAIRS = [
    ('navbar', '--toolbar-background-color', 'var(--toolbar-text-color)', 'var(--tf-bg)',
     'var(--tf-bg)', 'var(--tf-fg)'),
    ('urlbar', '--toolbar-field-background-color', 'var(--toolbar-field-text-color)', 'var(--tf-navbar-bg)',
     'var(--tf-navbar-bg)', 'var(--tf-navbar-fg)'),
    ('tab-selected', '--tab-background-color-selected', 'var(--tab-text-color-selected)', 'var(--tf-bg)',
     'color-mix(in hsl, var(--tf-fg) 8%, var(--tf-bg))', 'var(--tf-fg)'),
    ('popup', '--panel-background-color', 'var(--panel-text-color)', 'var(--tf-bg)',
     'var(--tf-bg)', 'var(--tf-fg)'),
    ('sidebar', '--sidebar-background-color', 'var(--sidebar-text-color)', 'var(--tf-bg)',
     'var(--tf-bg)', 'var(--tf-fg)'),
]
TEXT_RATIO = 4.5
ACCENT_RATIO = 3  # non-text contrast: focus rings and hover borders (V12)

HEADER = '''/* Generated by tools/firefox-chrome/gen-theme-css.py; edit that, not this file.

   Firefox theme colors onto textfox surfaces (V22). With a Firefox theme, each surface paints the
   theme's own color pair where the theme sets one and it reaches 4.5:1 as composited; otherwise
   --tf-bg with --tf-fg. --tf-theme-colors 0 turns the mapping off. defaults.css reads the results
   (--textfox-<surface>-bg/-fg) as the defaults of --tf-<surface>-bg/-fg, which config.css can set.

   No if() in Firefox: the pass/fail of each contrast test is a number carried as the alpha of
   black (-s), and each pick is premultiplied color-mix() arithmetic. See the generator's notes. */
'''


def over(top, under):
    """`top` composited over opaque `under` in srgb, as Firefox paints it; opaque result.
    `under` with alpha 1 - a(top) is recovered from a premultiplied mix with black at alpha a."""
    under_rest = (f'color(from color-mix(in srgb, {under}, color(from {top} srgb 0 0 0 / alpha)) srgb '
                  'calc(r * 2 * alpha) calc(g * 2 * alpha) calc(b * 2 * alpha) / calc(2 - 2 * alpha))')
    return f'color(from color-mix(in srgb, {top}, {under_rest}) srgb r g b / 1)'


def passes(bg, fg, ratio, switch='var(--tf-theme-colors)'):
    """Black whose alpha is 1 when bg and fg (opaque) reach `ratio`, else 0; times the switch."""
    pack = (f'color-mix(in xyz-d65, color(from {bg} xyz-d65 y 0 0 / 1), '
            f'color(from {fg} xyz-d65 0 y 0 / 1))')
    a, b = '(2 * x + 0.05)', '(2 * y + 0.05)'
    test = f'max({a} - {ratio} * {b}, {b} - {ratio} * {a})'
    return (f'color(from {pack} xyz-d65 0 0 0 / '
            f'calc(clamp(0, {test} * 100000, 1) * clamp(0, {switch}, 1)))')


def with_alpha_of(color, carrier):
    """Opaque `color` with the alpha of black `carrier`, recovered from their premultiplied mix."""
    return (f'color(from color-mix(in xyz-d65, color(from {color} xyz-d65 x y z / 1), {carrier}) xyz-d65 '
            'calc(x * 2 * alpha) calc(y * 2 * alpha) calc(z * 2 * alpha) / calc(2 * alpha - 1))')


def pick(s, theme, fallback):
    """`theme` (opaque) where black `s` has alpha 1, `fallback` (alpha kept) where 0; srgb result."""
    not_s = f'color(from {s} xyz-d65 0 0 0 / calc(1 - alpha))'
    mixed = (f'color-mix(in xyz-d65, {with_alpha_of(theme, s)}, {with_alpha_of(fallback, not_s)})')
    # Final alpha s + (1 - s) * alpha(fallback), packed from the two alphas.
    alphas = (f'color-mix(in xyz-d65, color(from {fallback} xyz-d65 alpha 0 0 / 1), '
              f'color(from {s} xyz-d65 0 alpha 0 / 1))')
    carrier = f'color(from {alphas} xyz-d65 0 0 0 / calc(2 * y + (1 - 2 * y) * 2 * x))'
    return f'color(from {with_alpha_of(mixed, carrier)} srgb r g b / alpha)'


def pair_block(name, key, text, backing, fallback_bg, fallback_fg):
    v = f'--textfox-{name}'
    # Over theme art (V19) boxes are transparent; the URL bar field keeps the theme's own field
    # and text where its pair passes, as Firefox paints it over the art (B27), else --tf-fg.
    art = (f"\n  {v}-art: {pick(f'var({v}-s)', f'var({v}-o)', 'transparent')};"
           f"\n  {v}-art-bg: {pick(f'var({v}-s)', f'var({v}-o)', 'var(--tf-bg)')};"
           f"\n  {v}-art-fg: {pick(f'var({v}-s)', f'var({v}-t)', 'var(--tf-fg)')};" if name == 'urlbar' else '')
    return f'''
/* {name}: {key} with its text, over {backing}. */
:root[lwtheme][style*="{key}:"] {{
  {v}-o: {over(f'var({key})', backing)};
  {v}-t: {over(text, f'var({v}-o)')};
  {v}-s: {passes(f'var({v}-o)', f'var({v}-t)', TEXT_RATIO)};
  {v}-bg: {pick(f'var({v}-s)', f'var({v}-o)', fallback_bg)};
  {v}-fg: {pick(f'var({v}-s)', f'var({v}-t)', fallback_fg)};{art}
}}
'''


def registered(names):
    """Intermediate colors registered as <color>: each computes once to one color on :root, so the
    picks that read them stay short (unregistered custom properties expand as text)."""
    return ''.join(f'@property {n} {{ syntax: "<color>"; inherits: true; initial-value: transparent; }}\n'
                   for n in names)


def css():
    out = [HEADER, '\n', registered(
        ['--textfox-window-t', '--textfox-window-s', '--textfox-accent-o', '--textfox-accent-s'] +
        [f'--textfox-{p[0]}-{k}' for p in PAIRS for k in 'ots'])]
    out.append(f'''
/* window and tab strip: --tf-bg (frame) with the theme's tab_background_text. */
:root[lwtheme] {{
  --textfox-window-t: {over('var(--lwt-text-color)', 'var(--tf-bg)')};
  --textfox-window-s: {passes('var(--tf-bg)', 'var(--textfox-window-t)', TEXT_RATIO)};
  --textfox-window-fg: {pick('var(--textfox-window-s)', 'var(--textfox-window-t)', 'contrast-color(var(--tf-bg))')};
}}
''')
    for p in PAIRS:
        out.append(pair_block(*p))
    out.append(f'''
/* accent: the theme's tab_line where it reaches 3:1 against --tf-bg (non-text contrast). */
:root[lwtheme][style*="--lwt-tab-line-color:"] {{
  --textfox-accent-o: {over('var(--lwt-tab-line-color)', 'var(--tf-bg)')};
  --textfox-accent-s: {passes('var(--tf-bg)', 'var(--textfox-accent-o)', ACCENT_RATIO)};
  --textfox-accent: {pick('var(--textfox-accent-s)', 'var(--textfox-accent-o)', 'var(--toolbarbutton-icon-fill)')};
}}
''')
    return ''.join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true', help='exit 1 if chrome/theme.css is stale')
    args = parser.parse_args()
    text = css()
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f'{OUT} is stale; run {Path(__file__).name}')
        print(f'{OUT.name} up to date')
        return
    OUT.write_text(text)
    print(f'wrote {OUT}')


if __name__ == '__main__':
    main()
