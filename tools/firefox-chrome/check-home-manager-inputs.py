#!/usr/bin/env python3
"""Check the files the home-manager module reads against the tree that ships them.

Home Manager cannot be evaluated here (no source offline, and `packages.default`
cannot be built in this sandbox), so this pins the parts that can be checked: the
module's inputs still exist with the shape it assumes, and the tree it copies is
the import-based source tree — not the NixOS build layout with its digest-named
asset directory.

Exit 0 means the module's expectations and the shipped tree still agree.
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
MODULE = ROOT / "nix" / "modules" / "home-manager.nix"
PACKAGE = ROOT / "nix" / "pkgs" / "default.nix"


def main() -> int:
    module = MODULE.read_text()
    chrome = ROOT / "chrome"

    # What the module reads from the package, and what it expects where.
    reads = re.findall(r'\$\{package\}/([^"]+)', module)
    assert "user.js" in reads, f"module no longer reads user.js: {reads}"
    assert "chrome/userChrome.css" in reads, f"module no longer reads chrome/userChrome.css: {reads}"
    assert "chrome" in reads, f"module no longer copies the chrome directory: {reads}"
    assert (ROOT / "user.js").is_file(), "user.js must exist for the module to read it"

    # The entry point it installs as `userChrome` is the import list, not a
    # concatenation: home-manager delivery has no concatenation step.
    entry = (chrome / "userChrome.css").read_text()
    imports = re.findall(r'@import\s+url\("([^"]+)"\)', entry)
    assert imports, "chrome/userChrome.css must stay an @import entry point for this path"
    for target in imports:
        if target == "config.css":
            # Generated by the module and by every user; never shipped.
            assert not (chrome / target).exists(), (
                "chrome/config.css must not exist in the tree: the module generates it"
            )
            assert "config.css" in module, "the module must still write chrome/config.css"
            continue
        assert (chrome / target).is_file(), f"imported sheet is missing: {target}"
    assert "config.css" in imports, "userChrome.css must import config.css last for overrides"

    # The copied tree keeps relative asset references; the digest-named directory
    # belongs to the NixOS build only and must not appear here.
    for sheet in chrome.rglob("*.css"):
        text = sheet.read_text()
        assert "textfox-assets-" not in text, f"{sheet} references a NixOS build asset directory"
        assert "/nix/store" not in text, f"{sheet} references a store path"
    icons_css = (chrome / "icons.css").read_text()
    assert "./icons/" in icons_css, "chrome/icons.css must reference ./icons/ relatively"

    # The package the module consumes copies chrome/ verbatim.
    package = PACKAGE.read_text()
    assert "chrome" in package, "nix/pkgs/default.nix must still ship chrome/"
    assert "user.js" in package, "nix/pkgs/default.nix must still ship user.js"

    print("ok   home-manager reads user.js, chrome/ and chrome/userChrome.css")
    print(f"ok   userChrome.css is an import list of {len(imports)} sheets, all present")
    print("ok   the shipped tree references icons relatively and ships no config.css")
    print("\nhome-manager inputs hold")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except AssertionError as error:
        print(f"not ok {error}")
        sys.exit(1)
